create function pg_temp.actor(p_device boolean) returns void language plpgsql as $$
declare actor uuid:=case when p_device then 'a0400000-0000-0000-0000-000000000022'::uuid else 'a0400000-0000-0000-0000-000000000021'::uuid end;
begin
 perform set_config('request.jwt.claim.sub',actor::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',actor,'role','authenticated','session_id',case when p_device then 'a0400000-0000-0000-0000-000000000091' else 'a0400000-0000-0000-0000-000000000090' end)::text,true);
end $$;

do $$
declare t uuid:='a0400000-0000-0000-0000-000000000041'; a uuid:='a0400000-0000-0000-0000-000000000031'; b uuid:='a0400000-0000-0000-0000-000000000032';
 branch uuid:='a0400000-0000-0000-0000-000000000011'; company uuid:='a0400000-0000-0000-0000-000000000001';
 pin text:=encode(extensions.gen_random_bytes(4),'hex'); physical text:=gen_random_uuid()::text||gen_random_uuid()::text; old_physical text; proof text; old_proof text;
 code jsonb; result jsonb; shift public.cashier_shifts; security_shift public.cashier_shifts; binding uuid; other_terminal public.pos_terminals;
begin
 perform pg_temp.actor(false);
 update public.pos_terminals set branch_id=branch,company_id=company,access_mode='ALL_BRANCH_STAFF',status='ACTIVE',registration_status='UNREGISTERED',auth_user_id=null,device_identifier=null where id=t;
 update public.staff set role_id=(select id from public.roles where name='CASHIER' and company_id=company),active=true where id in (a,b);
 -- PINs and device credentials are generated only in this rollback transaction, never printed.
 pin:=lpad((get_byte(extensions.gen_random_bytes(1),0)*1000)::text,6,'0');
 update public.staff_pin_credentials_v2 set pin_hash=extensions.crypt(pin,extensions.gen_salt('bf')) where staff_id in (a,b);
 code:=public.create_terminal_activation_code(t,true);
 perform pg_temp.actor(true);
 result:=public.activate_terminal_with_code(code->>'code',physical,'QA device');
 if result->>'ok'<>'true' then raise exception 'Activation failed: %',result->>'code'; end if;
 proof:=result->>'terminalCredential';
 if proof=physical or length(proof)<>64 then raise exception 'Activation did not issue an independent secure credential'; end if;
 if exists(select 1 from public.terminal_activation_codes where terminal_id=t and (used_at is null or display_code is not null)) then raise exception 'Code was not consumed'; end if;
 perform set_config('request.headers',jsonb_build_object('x-pos-device-credential',proof)::text,true);
 result:=public.resolve_authenticated_terminal(physical);
 if result->>'ok'<>'true' then raise exception 'Device binding failed: %',result->>'code'; end if;
 select assignment_id into binding from public.terminal_device_assignments where terminal_id=t and status='ACTIVE';
 result:=public.activate_terminal_with_code(code->>'code',physical,'Reuse denied');
 if result->>'ok'='true' then raise exception 'Consumed activation code reused'; end if;
 perform pg_temp.actor(false);
 other_terminal:=public.save_terminal_with_access(null,branch,'QA_DEVICE_COLLISION','Device collision test','CASHIER','ALL_BRANCH_STAFF','{}');
 code:=public.create_terminal_activation_code(other_terminal.id,true);
 perform pg_temp.actor(true);
 result:=public.activate_terminal_with_code(code->>'code',physical,'Duplicate device');
 if result->>'code'<>'DEVICE_ALREADY_BOUND' or not exists(select 1 from public.terminal_device_assignments where assignment_id=binding and status='ACTIVE') then raise exception 'Physical device was bound to two terminals'; end if;
 result:=public.login_terminal_staff(a,pin);
 if result->>'ok'<>'true' or (public.current_terminal_staff_session()).device_assignment_id<>binding then raise exception 'TEST 1: eligible all-branch staff rejected'; end if;
 perform public.end_terminal_staff_session();
 if not exists(select 1 from public.terminal_device_assignments where assignment_id=binding and status='ACTIVE') or (select registration_status from public.pos_terminals where id=t)<>'REGISTERED' then raise exception 'TEST 5: staff sign-out unbound device'; end if;
 result:=public.login_terminal_staff(b,pin);
 if result->>'ok'<>'true' then raise exception 'TEST 6: next staff required reactivation'; end if;
 perform public.end_terminal_staff_session();
 update public.staff_branch_assignments set status='INACTIVE' where staff_id='a0400000-0000-0000-0000-000000000022' and branch_id=branch;
 result:=public.login_terminal_staff(b,pin);
 if result->>'code'<>'STAFF_OUTLET_ACCESS_DENIED' then raise exception 'TEST 2: unrelated branch allowed'; end if;
 update public.staff_branch_assignments set status='ACTIVE' where staff_id='a0400000-0000-0000-0000-000000000022' and branch_id=branch;
 perform pg_temp.actor(false);
 perform public.save_terminal_access(t,'SELECTED_STAFF','{}',array[a]);
 perform pg_temp.actor(true);
 result:=public.login_terminal_staff(b,pin);
 if result->>'code'<>'STAFF_TERMINAL_ACCESS_DENIED' then raise exception 'TEST 4: unselected staff allowed'; end if;
 result:=public.login_terminal_staff(a,pin);
 if result->>'ok'<>'true' then raise exception 'TEST 3: selected staff rejected'; end if;
 update public.staff_branch_assignments set status='INACTIVE' where staff_id='a0400000-0000-0000-0000-000000000021' and branch_id=branch;
 result:=public.login_terminal_staff(a,pin);
 if result->>'code'<>'STAFF_OUTLET_ACCESS_DENIED' or (public.current_terminal_staff_session()).id is not null then raise exception 'TEST 11: selection bypassed revoked branch'; end if;
 update public.staff_branch_assignments set status='ACTIVE' where staff_id='a0400000-0000-0000-0000-000000000021' and branch_id=branch;
 update public.pos_terminals set lock_status='LOCKED' where id=t;
 if public.login_terminal_staff(a,pin)->>'code'<>'TERMINAL_LOCKED' then raise exception 'TEST 12: locked terminal allowed'; end if;
 update public.pos_terminals set lock_status='UNLOCKED' where id=t;
 update public.branches set status='INACTIVE' where id=branch;
 if public.login_terminal_staff(a,pin)->>'code'<>'BRANCH_INACTIVE' then raise exception 'TEST 13: inactive branch allowed'; end if;
 update public.branches set status='ACTIVE' where id=branch;
 update public.companies set status='INACTIVE' where id=company;
 if public.login_terminal_staff(a,pin)->>'code'<>'COMPANY_INACTIVE' then raise exception 'TEST 14: inactive company allowed'; end if;
 update public.companies set status='ACTIVE' where id=company;
 update public.staff set active=false where id=a;
 if public.login_terminal_staff(a,pin)->>'code'<>'STAFF_INACTIVE' then raise exception 'TEST 15: inactive staff allowed'; end if;
 update public.staff set active=true where id=a;
 perform set_config('request.headers','{}',true);
 if public.login_terminal_staff(a,pin)->>'code'<>'DEVICE_AUTHENTICATION_INVALID' then raise exception 'Missing device proof allowed'; end if;
 perform set_config('request.headers',jsonb_build_object('x-pos-device-credential',physical)::text,true);
 if public.resolve_authenticated_terminal(physical)->>'ok'='true' then raise exception 'Public physical identifier accepted as credential'; end if;
 perform set_config('request.headers',jsonb_build_object('x-pos-device-credential',proof)::text,true);
 result:=public.login_terminal_staff(a,pin);
 if result->>'ok'<>'true' then raise exception 'Restored login failed'; end if;
 perform public.lock_terminal_staff_session();
 if (public.current_terminal_staff_session()).id is not null then raise exception 'Locked staff session retained operational access'; end if;
 if not public.verify_own_terminal_lock_pin(pin) then raise exception 'Staff could not unlock using their own current PIN'; end if;
 shift:=public.open_cashier_shift(10);
 begin perform public.end_terminal_staff_session(); raise exception 'Open-shift sign-out allowed'; exception when raise_exception then if sqlerrm<>'ACTIVE_SHIFT_SIGN_OUT_BLOCKED' then raise; end if; end;
 perform pg_temp.actor(false);
 begin perform public.manage_terminal_device(t,'UNBIND'); raise exception 'TEST 16: open-shift unbind allowed'; exception when raise_exception then if sqlerrm<>'ACTIVE_SHIFT_DEVICE_CHANGE_BLOCKED' then raise; end if; end;
 if not exists(select 1 from public.terminal_staff_sessions where terminal_id=t and status='ACTIVE') then raise exception 'Failed unbind destroyed active staff'; end if;
 perform pg_temp.actor(true);
 perform public.close_cashier_shift(shift.id,10);
 perform pg_temp.actor(false);
 perform public.manage_terminal_device(t,'UNBIND');
 if exists(select 1 from public.terminal_device_assignments where terminal_id=t and status='ACTIVE') or exists(select 1 from public.terminal_staff_sessions where terminal_id=t and status in ('ACTIVE','LOCKED')) or (select status from public.pos_terminals where id=t)<>'ACTIVE' then raise exception 'TEST 7: unbind failed'; end if;
 if not exists(select 1 from public.terminal_staff_access where terminal_id=t and staff_id=a) then raise exception 'Unbind removed staff configuration'; end if;
 code:=public.create_terminal_activation_code(t,true);
 old_physical:=physical; old_proof:=proof; physical:=gen_random_uuid()::text||gen_random_uuid()::text;
 perform pg_temp.actor(true);
 result:=public.activate_terminal_with_code(code->>'code',physical,'Replacement device');
 if result->>'ok'<>'true' then raise exception 'TEST 8: replacement activation failed: %',result->>'code'; end if;
 proof:=result->>'terminalCredential';
 perform set_config('request.headers',jsonb_build_object('x-pos-device-credential',proof)::text,true);
 if public.resolve_authenticated_terminal(physical)->>'ok'<>'true' or public.login_terminal_staff(a,pin)->>'ok'<>'true' then raise exception 'TEST 8: selected access not preserved'; end if;
 security_shift:=public.open_cashier_shift(5);
 perform pg_temp.actor(false);
 perform public.manage_terminal_device(t,'REVOKE','Lost device test');
 if not exists(select 1 from public.cashier_shifts where id=security_shift.id and status='OPEN') then raise exception 'Security revocation destroyed the open shift'; end if;
 begin perform public.manage_terminal_device(t,'REACTIVATE'); raise exception 'Unreconciled revoked shift allowed reactivation'; exception when raise_exception then if sqlerrm<>'ACTIVE_SHIFT_DEVICE_CHANGE_BLOCKED' then raise; end if; end;
 perform public.force_close_cashier_shift(security_shift.id,5,'Lost device reconciliation');
 perform pg_temp.actor(true);
 if public.login_terminal_staff(a,pin)->>'ok'='true' or (public.current_terminal_staff_session()).id is not null then raise exception 'TEST 9: revoked device still active'; end if;
 if public.resolve_authenticated_terminal(physical)->>'ok'='true' then raise exception 'TEST 10: revoked credential reconnected'; end if;
 perform pg_temp.actor(false);
 code:=public.manage_terminal_device(t,'REACTIVATE');
 physical:=gen_random_uuid()::text||gen_random_uuid()::text;
 perform pg_temp.actor(true);
 result:=public.activate_terminal_with_code(code->>'code',physical,'Reactivated device');
 if result->>'ok'<>'true' then raise exception 'Reactivation failed: %',result->>'code'; end if;
 proof:=result->>'terminalCredential';
 perform set_config('request.headers',jsonb_build_object('x-pos-device-credential',old_proof)::text,true);
 if public.resolve_authenticated_terminal(physical)->>'ok'='true' then raise exception 'Replacement accepted old credential'; end if;
 perform set_config('request.headers',jsonb_build_object('x-pos-device-credential',proof)::text,true);
 if public.resolve_authenticated_terminal(physical)->>'ok'<>'true' then raise exception 'New credential rejected'; end if;
 perform pg_temp.actor(false);
 code:=public.manage_terminal_device(t,'REPLACE');
 if not exists(select 1 from public.cashier_shifts where id=shift.id and status='CLOSED') or not exists(select 1 from public.terminal_staff_access where terminal_id=t and staff_id=a) then raise exception 'Replacement destroyed historical/configuration records'; end if;
 if not exists(select 1 from public.audit_logs where action='STAFF_LOGOUT' and terminal_id=t and staff_session_id is not null) or not exists(select 1 from public.audit_logs where action='TERMINAL_DEVICE_REPLACED' and terminal_id=t and company_id=company and branch_id=branch) then raise exception 'Lifecycle audit context incomplete'; end if;
 if has_column_privilege('authenticated','public.terminal_device_assignments','credential_hash','SELECT') or has_column_privilege('authenticated','public.pos_terminals','device_identifier','SELECT') or has_function_privilege('authenticated','public.activate_terminal_with_code(text,text)','EXECUTE') then raise exception 'Credential material or activation bypass exposed'; end if;
 raise notice 'VERIFIED PASS: 16 terminal/device scenarios, credential proof, consumed code, shift safety, replacement/reactivation, audit and history preservation';
end $$;
rollback;
